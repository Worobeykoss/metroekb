def parse_block(text):
    """Многострочный блок "HH: mins" -> {hour:int -> [minutes]}."""
    table = {}
    for line in text.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        hh, mins = line.split(":", 1)
        table[int(hh)] = parse_minutes(mins)
    return table


